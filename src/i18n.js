const DICT = {zh: ZH, en: EN};

export function t(key, vars = {}) {
  const s = DICT[LANG][key] ?? ZH[key];
  if (s == null) return key;
  return typeof s === 'function' ? s(vars) : s;
}

/* 测试用：两种语言的 key 是否一致 */
export function missingKeys() {
  return {en: Object.keys(ZH).filter(k => !(k in EN)), zh: Object.keys(EN).filter(k => !(k in ZH))};
}
