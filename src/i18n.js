// - t(key, vars)：取当前语言的文字；值可以是字符串（{name} 占位）或函数 vars => 字符串
// - 中文是原来的文字，一字不改（测试按中文断言）；英文缺了某个 key 时退回中文
// - 语言只是模块里的一个变量：浏览器里由界面开关设置，Node 测试默认中文，可以 setLang('en') 测英文
let LANG = 'zh';
export const LANGS = ['zh', 'en'];
export function setLang(l) { LANG = l === 'en' ? 'en' : 'zh'; }
export function getLang() { return LANG; }
export const isEn = () => LANG === 'en';

/* 取对象里当前语言的字段：英文时优先 obj.en[field]，没有就用 obj[field] */
export function loc(obj, field) {
  if (!obj) return '';
  if (LANG === 'en' && obj.en && obj.en[field] != null) return obj.en[field];
  return obj[field];
}

